# =============================================================================
# tools/script_inventory.R
#
# Static scan of the R scripts in 02_Scripts/ (top level only; "old codes/" is
# listed but not scanned in detail). For each script it extracts, by regular
# expression on the source text:
#   - inputs   : load(), readRDS(), read.csv(), read_excel(), read_xlsx(), fread()
#   - outputs  : save(), saveRDS(), ggsave(), write_xlsx(), write.csv(),
#                save_as_docx(), print(<docx>, target=), png()/pdf()
#   - sourced  : source(), sys.source(), parse() of other scripts
#   - seeds    : set.seed() calls
#   - paths    : absolute paths (drive letters, /Users/, OneDrive)
#   - packages : library()/require()/pacman::p_load()
#
# This is a static scan, not an execution trace: paths built at run time
# (paste0/sprintf/file.path with variables) are reported as written in the
# source and may need manual interpretation.
#
# Usage (from the project root):
#   Rscript tools/script_inventory.R            # writes docs/SCRIPT_INVENTORY.md
#   Rscript tools/script_inventory.R --csv      # also writes docs/script_inventory.csv
# =============================================================================

args <- commandArgs(trailingOnly = TRUE)
if (!dir.exists("02_Scripts")) stop("Run from the project root (02_Scripts/ not found).")

scripts <- sort(list.files("02_Scripts", pattern = "\\.R$", full.names = TRUE))

# Strip comments so commented-out loads/saves are not reported. Keeps '#'
# inside quoted strings (rough: only handles lines without escaped quotes).
strip_comments <- function(lines) {
  vapply(lines, function(l) {
    out <- ""; in_s <- FALSE; q <- ""
    for (ch in strsplit(l, "")[[1]]) {
      if (!in_s && ch == "#") break
      if (!in_s && ch %in% c("\"", "'")) { in_s <- TRUE; q <- ch }
      else if (in_s && ch == q) in_s <- FALSE
      out <- paste0(out, ch)
    }
    out
  }, character(1), USE.NAMES = FALSE)
}

grab <- function(txt, pattern) {
  m <- regmatches(txt, gregexpr(pattern, txt, perl = TRUE))
  unique(trimws(unlist(m)))
}

first_string <- function(calls) {
  # first quoted string that looks like a path (has "/" or a file extension),
  # else the call text: e.g. ggsave(out_file, p, bg = "white") reports the
  # call, not "white"
  vapply(calls, function(x) {
    s <- gsub("^[\"']|[\"']$", "", regmatches(x, gregexpr("\"[^\"]+\"|'[^']+'", x))[[1]])
    s <- s[grepl("/|\\.[A-Za-z]{2,5}$", s)]
    if (length(s)) s[1] else gsub("\\s+", " ", x)
  }, character(1), USE.NAMES = FALSE)
}

scan_script <- function(f) {
  raw <- readLines(f, warn = FALSE, encoding = "UTF-8")
  code <- strip_comments(raw)
  txt <- paste(code, collapse = "\n")
  header <- raw[seq_len(min(length(raw), 25))]
  header <- header[grepl("^#", header)]

  in_calls  <- grab(txt, "(load|readRDS|read\\.csv|read_excel|read_xlsx|fread|read\\.xlsx)\\s*\\([^)]*\\)")
  out_calls <- grab(txt, "(\\bsave|saveRDS|ggsave|write_xlsx|write\\.csv|save_as_docx|write\\.xlsx|png|pdf)\\s*\\([^)]*\\)")
  src_calls <- grab(txt, "(sys\\.source|source|parse)\\s*\\([^)]*\\)")
  seeds     <- grab(txt, "set\\.seed\\s*\\([^)]*\\)")
  abs_paths <- grab(txt, "[\"'](?:[A-Za-z]:[/\\\\]|/Users/|~/)[^\"']*[\"']")
  setwd_c   <- grab(txt, "setwd\\s*\\([^)]*\\)")
  pkgs <- c(
    grab(txt, "(?<=library\\()[A-Za-z0-9.]+"),
    grab(txt, "(?<=require\\()[A-Za-z0-9.]+"),
    unlist(lapply(grab(txt, "p_load\\s*\\([^)]*\\)"), function(x) {
      y <- sub("^p_load\\s*\\(", "", sub("\\)$", "", x))
      trimws(strsplit(gsub("\\s+", " ", y), ",")[[1]])
    }))
  )
  pkgs <- sort(unique(pkgs[nzchar(pkgs)]))

  list(
    script   = basename(f),
    lines    = length(raw),
    header   = paste(sub("^#\\s?", "", header), collapse = " "),
    inputs   = unique(first_string(in_calls)),
    outputs  = unique(first_string(out_calls)),
    sourced  = unique(first_string(src_calls)),
    seeds    = seeds,
    abs_paths = unique(gsub("[\"']", "", abs_paths)),
    setwd    = setwd_c,
    packages = pkgs
  )
}

inv <- lapply(scripts, scan_script)

collapse <- function(x, sep = "<br>") if (length(x)) paste(x, collapse = sep) else ""
esc <- function(x) gsub("\\|", "\\\\|", x)

md <- c(
  "# Script inventory (static scan)",
  "",
  "Generated by `Rscript tools/script_inventory.R`. This is a **static text scan** of",
  "`02_Scripts/*.R`, not an execution trace: file names assembled at run time",
  "(`paste0()`, `sprintf()`, `file.path()` with variables) appear as written in the",
  "source. Commented-out code is excluded. See `docs/FIGURE_TABLE_REPRODUCTION_MAP.md`",
  "for which scripts produce the submitted manuscript outputs.",
  "",
  sprintf("Scripts scanned: %d (top level of `02_Scripts/`; `02_Scripts/old codes/` is legacy and not scanned).", length(inv)),
  ""
)
for (s in inv) {
  md <- c(md,
    sprintf("## %s (%d lines)", s$script, s$lines),
    "",
    if (nzchar(s$header)) c(paste0("> ", substr(esc(s$header), 1, 600)), "") else NULL,
    "| Field | Value |", "|---|---|",
    sprintf("| Inputs | %s |", esc(collapse(paste0("`", s$inputs, "`")[length(s$inputs) > 0]))),
    sprintf("| Outputs | %s |", esc(collapse(paste0("`", s$outputs, "`")[length(s$outputs) > 0]))),
    sprintf("| Sources / parses | %s |", esc(collapse(paste0("`", s$sourced, "`")[length(s$sourced) > 0]))),
    sprintf("| RNG | %s |", esc(collapse(paste0("`", s$seeds, "`")[length(s$seeds) > 0]))),
    sprintf("| Absolute paths | %s |", esc(collapse(paste0("`", c(s$abs_paths, s$setwd), "`")[length(c(s$abs_paths, s$setwd)) > 0]))),
    sprintf("| Packages | %s |", esc(collapse(s$packages, ", "))),
    ""
  )
}
writeLines(md, "docs/SCRIPT_INVENTORY.md", useBytes = TRUE)
message("Wrote docs/SCRIPT_INVENTORY.md (", length(inv), " scripts)")

if ("--csv" %in% args) {
  df <- data.frame(
    script = vapply(inv, `[[`, "", "script"),
    lines = vapply(inv, `[[`, 0L, "lines"),
    inputs = vapply(inv, function(s) collapse(s$inputs, "; "), ""),
    outputs = vapply(inv, function(s) collapse(s$outputs, "; "), ""),
    sourced = vapply(inv, function(s) collapse(s$sourced, "; "), ""),
    seeds = vapply(inv, function(s) collapse(s$seeds, "; "), ""),
    abs_paths = vapply(inv, function(s) collapse(c(s$abs_paths, s$setwd), "; "), ""),
    packages = vapply(inv, function(s) collapse(s$packages, "; "), ""),
    stringsAsFactors = FALSE
  )
  write.csv(df, "docs/script_inventory.csv", row.names = FALSE)
  message("Wrote docs/script_inventory.csv")
}
